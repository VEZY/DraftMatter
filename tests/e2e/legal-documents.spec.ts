import { expect, test } from '@playwright/test'

test('reads the alpha documents without signing in and preserves browser navigation', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Pre-production: data loss is possible. Keep independent backups of your work outside DraftMatter.', { exact: true })).toBeVisible()
  await page.locator('footer').getByRole('link', { name: 'Privacy policy', exact: true }).click()
  await expect(page).toHaveURL(/\/legal\/confidentialite$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Privacy policy')
  await expect(page.locator('main')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused()
  await expect(page.locator('a[href="mailto:vezy.remi@gmail.com"]').first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Privacy policy')
  await page.locator('footer').getByRole('link', { name: 'Terms of use', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Terms of use')
  await page.goBack()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Privacy policy')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your papers')
})

test('keeps long legal pages usable on a small screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/legal/conditions-utilisation')
  await expect(page.getByRole('heading', { name: 'Terms of use', exact: true })).toBeVisible()
  const bounds = await page.locator('main').evaluate((element) => ({ width: element.clientWidth, scrollWidth: element.scrollWidth }))
  expect(bounds.width).toBeLessThanOrEqual(390)
  expect(bounds.scrollWidth).toBeLessThanOrEqual(bounds.width)
  await page.getByRole('link', { name: 'Legal notice', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Legal notice')
})

test('explains data-loss risk and independent backups before using the pre-production service', async ({ page }) => {
  await page.goto('/legal/conditions-utilisation')
  const warning = page.getByRole('heading', { name: 'Testing and data loss', exact: true }).locator('..')
  await expect(warning).toContainText(/pre-production/i)
  await expect(warning).toContainText(/data loss/i)
  await expect(warning).toContainText(/independent backups/i)
  await expect(warning).toContainText(/outside (?:DraftMatter|the service)/i)
  await expect(warning).toContainText(/synchroni[sz]ation/i)
  await expect(warning).toContainText(/history/i)
  await expect(warning).toContainText(/server backups/i)
  await expect(warning).toContainText(/You are .*responsible .*independent backups/i)
  await expect(warning).toContainText(/Synchroni[sz]ation, version history and server backups do not replace independent backups/i)
  await expect(page.locator('article')).toContainText(/(?:mandatory|statutory).*rights|rights.*(?:mandatory|statutory)/i)
  await expect(page.locator('article')).not.toContainText(/Docker|PostgreSQL|\bS3\b|Keycloak|\bVPS\b/i)
})
