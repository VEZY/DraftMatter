import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test.describe('DM-P0-06 rendered vertical slice', () => {
  test('renders, reviews, and projects the portable manuscript without exposing review source', async ({ page }) => {
    await page.addInitScript(() => {
      Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: undefined })
    })
    await page.goto('/draft')
    await page.locator('.topbar').getByRole('button', { name: /^Review,/ }).click()

    const manuscript = page.getByRole('article', { name: 'Editable manuscript' })
    const reviewPanel = page.getByRole('complementary', { name: 'Review feedback' })

    await expect(manuscript).toBeVisible()
    await expect(page.getByRole('textbox', { name: 'Manuscript title' })).toContainText('Drought acclimation reshapes canopy development')
    await expect(manuscript.getByLabel('Publication authors')).toContainText('Remi Vezy')
    await expect(manuscript.getByLabel('Publication authors')).toContainText('Alice Martin')
    await expect(manuscript).not.toContainText('CIRAD, UMR AMAP')
    await expect(manuscript).not.toContainText('Keywords drought acclimation')
    await expect(page.getByRole('button', { name: 'Edit citation @vezy2024' })).toHaveText('(Vezy et al., 2024)')
    await expect(page.locator('.structured-code-cell-header')).toContainText('Reproducible figure')
    await expect(page.locator('.structured-code-cell-header')).not.toContainText('fig-canopy')
    await expect(page.getByRole('img', { name: 'Leaf area response over twelve weeks' })).toBeVisible()
    await expect(reviewPanel.getByText('2 overlapping alternatives')).toBeVisible()
    await expect(reviewPanel.getByText(/Can we quantify this increase/)).toBeVisible()
    await expect(reviewPanel.locator('time[datetime="2026-07-15T09:00:00.000Z"]')).toHaveText('15 Jul 2026 · 09:00 UTC')
    await expect(reviewPanel.locator('time[datetime="2026-07-15T09:04:00.000Z"]')).toHaveText('15 Jul 2026 · 09:04 UTC')
    await expect(reviewPanel.locator('time[datetime="2026-07-15T09:08:00.000Z"]')).toHaveText('15 Jul 2026 · 09:08 UTC')
    await expect(reviewPanel).not.toContainText('minutes ago')
    const reviewPosition = reviewPanel.locator('.portable-review-footer span')
    const nextReview = reviewPanel.getByRole('button', { name: 'Next review item' })
    const previousReview = reviewPanel.getByRole('button', { name: 'Previous review item' })
    await expect(reviewPosition).toHaveText('1 of 3')
    await expect(page.locator('body')).not.toContainText('.dm-anchor')
    await expect(page.locator('body')).not.toContainText('.draftmatter-reviews')

    await expect(page).toHaveScreenshot('rendered-vertical-slice.png')

    await page.getByRole('button', { name: 'Export' }).click()
    await page.getByRole('button', { name: /Review report/ }).click()
    const reviewExport = page.getByRole('dialog', { name: 'Save review report' })
    await expect(reviewExport.getByLabel('File name')).toHaveValue('canopy-drought.review.md')
    const reviewDownloadPromise = page.waitForEvent('download')
    await reviewExport.getByRole('button', { name: 'Choose location…' }).click()
    const reviewDownload = await reviewDownloadPromise
    expect(reviewDownload.suggestedFilename()).toBe('canopy-drought.review.md')
    const reviewDownloadPath = await reviewDownload.path()
    expect(reviewDownloadPath).not.toBeNull()
    const reviewReport = await readFile(reviewDownloadPath!, 'utf8')
    expect(reviewReport).toContain('# DraftMatter review report')
    expect(reviewReport).toContain('Can we quantify this increase in the main text?')
    expect(reviewReport).not.toMatch(/\.draftmatter-reviews|\.dm-(?:anchor|change|thread|decision)|data-anchor=/)

    await nextReview.click()
    await expect(reviewPosition).toHaveText('2 of 3')
    await expect(reviewPanel.locator('#review-item-dm-c02')).toHaveClass(/selected/)
    await nextReview.click()
    await expect(reviewPosition).toHaveText('3 of 3')
    await expect(reviewPanel.locator('#review-item-dm-comment-01')).toHaveClass(/active/)
    await previousReview.click()
    await expect(reviewPosition).toHaveText('2 of 3')

    await page.getByRole('button', { name: /View source/ }).click()
    const sourceInspector = page.getByRole('dialog', { name: 'Portable source inspector' })
    await sourceInspector.getByRole('tab', { name: 'Clean final' }).click()
    await expect(sourceInspector.getByRole('alert')).toContainText('dm-c01 (Alice Martin, open); dm-c02 (Marcus Chen, open)')
    await expect(sourceInspector.getByRole('button', { name: 'Resolve review first' })).toBeDisabled()

    await page.getByRole('button', { name: 'Close source inspector' }).click()
    await reviewPanel.locator('#review-item-dm-c02').click()
    await reviewPanel.getByRole('button', { name: 'Accept' }).click()
    await expect(reviewPanel.locator('#review-item-dm-c02')).toContainText('Accepted')
    await expect(reviewPanel.locator('#review-item-dm-c01')).toContainText('Needs rebase')
    await expect(reviewPanel.locator('#review-item-dm-c02 time')).toHaveAttribute('title', /^Updated /)
    await expect(reviewPanel.locator('#review-item-dm-c01 time')).toHaveAttribute('title', /^Updated /)

    await page.getByRole('button', { name: /View source/ }).click()
    await sourceInspector.getByRole('tab', { name: 'Clean final' }).click()
    const cleanProjection = sourceInspector.locator('pre')
    await expect(cleanProjection).toContainText('lowered leaf expansion during the treatment period')
    await expect(cleanProjection).not.toContainText('.dm-anchor')
    await expect(cleanProjection).not.toContainText('.draftmatter-reviews')
    await expect(sourceInspector.getByRole('button', { name: 'Download projection' })).toBeEnabled()
  })

  test('keeps the primary writing and review controls keyboard reachable', async ({ page }) => {
    await page.goto('/draft')
    await expect(page.getByRole('textbox', { name: 'Rendered manuscript editor' })).toBeVisible()

    await page.keyboard.press('Control+p')
    const palette = page.getByRole('dialog', { name: 'Command menu' })
    await expect(palette).toBeVisible()
    const commandSearch = palette.getByRole('textbox', { name: 'Search commands' })
    await commandSearch.fill('equation')
    await expect(palette.getByRole('button', { name: /Insert inline equation/ })).toHaveClass(/active/)
    await page.keyboard.press('ArrowDown')
    await expect(palette.getByRole('button', { name: /Insert display equation/ })).toHaveClass(/active/)
    await expect(commandSearch).toHaveAttribute('aria-activedescendant', 'command-display-equation')
    await commandSearch.fill('manuscript source')
    await expect(palette.getByRole('button', { name: /View manuscript source/ })).toBeVisible()
    await expect(palette.getByRole('button', { name: /Add section/ })).toBeHidden()
    await page.keyboard.press('Enter')
    const sourceInspector = page.getByRole('dialog', { name: 'Portable source inspector' })
    await expect(sourceInspector).toBeVisible()
    await sourceInspector.getByRole('button', { name: 'Close source inspector' }).click()

    await page.keyboard.press('Control+p')
    await expect(commandSearch).toHaveValue('')
    await page.keyboard.press('Escape')
    await expect(palette).toBeHidden()

    await page.getByRole('textbox', { name: 'Manuscript title' }).focus()
    await expect(page.getByRole('textbox', { name: 'Manuscript title' })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(page.locator(':focus')).toBeVisible()
  })
})
