import { expect, test } from '@playwright/test'

test('previews and retains project files beside the manuscript without replacing its editor', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/draft')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.locator('.project-switcher').click()
  await page.getByRole('button', { name: /Open complete example/ }).click()
  await page.locator('.structured-manuscript-editor').evaluate((editor) => { (window as unknown as { originalEditor: Element }).originalEditor = editor })
  await page.getByRole('button', { name: 'Browse project files', exact: true }).click()
  const files = page.getByRole('complementary', { name: 'Project file browser' })
  const scroll = await page.locator('.editor-area').evaluate((area) => { area.scrollTop = 200; return area.scrollTop })
  await files.getByTitle('Open data/canopy.csv', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Table preview', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: /canopy.csv/ })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Keep open', exact: true }).click()
  await files.getByTitle('Open figures/python-canopy.svg', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Image preview', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'figures/python-canopy.svg', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: /canopy.csv/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('files-and-image.png') })
  await page.getByRole('tab', { name: /Manuscript/ }).click()
  expect(await page.locator('.structured-manuscript-editor').evaluate((editor) => editor === (window as unknown as { originalEditor: Element }).originalEditor)).toBe(true)
  expect(await page.locator('.editor-area').evaluate((area) => area.scrollTop)).toBe(scroll)
  await expect(page.getByRole('textbox', { name: 'Rendered manuscript editor' })).toBeVisible()
  await page.getByRole('button', { name: 'Close project files', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('tab', { name: /canopy.csv/ })).toBeVisible()
  await expect(page.getByRole('tab', { name: /python-canopy.svg/ })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Browse project files', exact: true }).click()
  await page.getByTitle('Open data/allocation.csv', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Table preview', exact: true })).toBeVisible()
  await expect(files).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('file-preview-mobile.png') })
  expect(errors).toEqual([])
})
