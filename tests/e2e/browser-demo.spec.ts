test('accepting a tracked edit in the example abstract leaves ordinary editable text and can be undone', async ({ page }) => {
  await page.goto('/demo')
  const abstract = page.locator('.ProseMirror p').filter({ hasText: 'We created a complete' })
  await setTrackChanges(page)
  await selectRenderedTextWithMouse(page, abstract, 'synthetic')
  await page.keyboard.type('simulated')
  const scroller = page.locator('.editor-area')
  const typingScroll = await scroller.evaluate(element => element.scrollTop)
  const card = page.locator('[data-review-balloon]').filter({ hasText: 'imulated' })
  await expect(card).toBeVisible()
  await expect(abstract.locator('.dm-review-wording[data-proposal-id]')).toBeFocused()
  expect(Math.abs(await scroller.evaluate(element => element.scrollTop) - typingScroll)).toBeLessThan(5)
  await card.locator('.proposal-option').click()
  await card.getByRole('button', { name: 'Accept', exact: true }).click()
  await expect(abstract).toContainText('a complete, simulated drought-phenotyping study')
  await expect(abstract.locator('.dm-review-change, .dm-review-proposal, .dm-review-wording')).toHaveCount(0)
  await expect(card).toHaveCount(0)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(card).toHaveCount(1)
  await expect(abstract).toContainText('synthetic')
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(card).toHaveCount(0)
  await expect(abstract).toContainText('a complete, simulated drought-phenotyping study')
})

test('capturing a tracked edit near the end keeps the paper in place and lets the next click move the caret', async ({ page }) => {
  await page.goto('/demo')
  const editor = page.getByRole('textbox', { name: 'Rendered manuscript editor', exact: true })
  const scroller = page.locator('.editor-area')
  const finalParagraph = editor.locator('p').filter({ hasText: 'The complete source, review records' })
  const earlierParagraph = editor.locator('p').filter({ hasText: 'This example uses aggregate synthetic data' })
  const figures = editor.locator('.structured-output-content > img')
  await expect(figures).toHaveCount(3)
  await expect.poll(() => figures.evaluateAll(images => images.every(image =>
    image instanceof HTMLImageElement && image.complete && image.naturalHeight > 0))).toBe(true)
  const unchangedBlocks = await editor.locator('.structured-heading-card, .structured-output-content > img').elementHandles()

  await setTrackChanges(page)
  await finalParagraph.evaluate(element => element.scrollIntoView({ block: 'center' }))
  await selectRenderedTextWithMouse(page, finalParagraph, 'review records')
  const readScroll = () => scroller.evaluate(element => element.scrollTop)
  await page.keyboard.type('documentary trail')
  const typingScroll = await readScroll()
  const wording = finalParagraph.locator('.dm-review-wording[data-proposal-id]')
  await expect(wording).toBeFocused()
  await expect(wording).toHaveText('documentary trail')
  // Let the DOM observer and scroll event complete the suggestion handoff.
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  expect(Math.abs(await readScroll() - typingScroll)).toBeLessThan(30)

  await earlierParagraph.evaluate(element => element.scrollIntoView({ block: 'center' }))
  const earlierScroll = await readScroll()
  await earlierParagraph.click()
  const clickedHere = () => earlierParagraph.evaluate(paragraph => paragraph.contains(window.getSelection()?.focusNode ?? null))
  await expect.poll(clickedHere).toBe(true)
  expect(Math.abs(await readScroll() - earlierScroll)).toBeLessThan(12)
  for (const element of unchangedBlocks) expect(await element.evaluate(node => node.isConnected)).toBe(true)
})

test('the anonymous example supports editing and citations without reading, replacing or uploading a private draft', async ({ page, baseURL }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  const accountRequests: string[] = []
  const devSocketOrigin = baseURL?.replace(/^http/, 'ws')
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => {
    const url = new URL(request.url())
    if (url.pathname.startsWith('/api/') || url.pathname === '/config' || url.pathname.includes('/protocol/openid-connect/')) accountRequests.push(url.origin + url.pathname)
  })
  page.on('websocket', (socket) => {
    const url = new URL(socket.url())
    // Vite's development-only hot-reload socket is not an account connection.
    if (url.origin === devSocketOrigin && url.pathname === '/' && url.searchParams.has('token')) return
    accountRequests.push(socket.url())
  })
  await page.goto('/')
  const privateDraft = '# A private paper that must survive the example\n\nNever publish this text.\n'
  await page.evaluate((privateDraft) => {
    localStorage.setItem('draftmatter.structured-source.v1', privateDraft)
    localStorage.setItem('draftmatter.structured-mode.v1', 'true')
    localStorage.setItem('draftmatter.user-settings.v1', 'private-profile-sentinel')
    sessionStorage.setItem('draftmatter.collaboration.oidc.v1', 'private-login-sentinel')
  }, privateDraft)
  await page.goto('/demo?code=attacker-code&state=attacker-state#dm-invite=attacker-secret&dm-service=https%3A%2F%2Funtrusted.example.test')
  const editor = page.getByRole('textbox', { name: 'Rendered manuscript editor', exact: true })
  await expect(page.getByRole('complementary', { name: 'Interactive example', exact: true })).toBeVisible()
  await expect(editor).toBeVisible({ timeout: 30_000 })
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBe(await page.evaluate(() => innerHeight))
  expect(await page.locator('.workspace').evaluate((element) => element.getBoundingClientRect().bottom)).toBeLessThanOrEqual(await page.evaluate(() => innerHeight + 1))
  await expect(editor.getByRole('heading', { level: 1 })).toHaveText('A reproducible cross-language analysis of synthetic canopy drought responses')
  await expect(editor).not.toContainText('A private paper')
  expect(await page.evaluate(() => typeof indexedDB)).toBe('undefined')
  await expect(page.locator('.structured-output-image img')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Open online collaboration', exact: true })).toBeDisabled()
  const paragraph = editor.locator('p').filter({ hasText: 'drought' }).first()
  await paragraph.click()
  await page.keyboard.press('Home')
  await page.keyboard.type('Anonymous trial. ')
  await expect(editor).toContainText('Anonymous trial.')
  await showWritingTools(page)
  await page.getByRole('button', { name: 'Insert citation', exact: true }).click()
  const picker = page.getByRole('dialog', { name: 'Insert citation', exact: true })
  await expect(picker).toBeVisible()
  const source = picker.locator('.source-result').first()
  await expect(source).toBeVisible()
  await source.click()
  await picker.getByRole('button', { name: /^Insert selected/ }).click()
  await expect(picker).toBeHidden()
  expect(accountRequests).toEqual([])
  expect(errors).toEqual([])
  await page.getByRole('link', { name: 'Reset example', exact: true }).click()
  await expect(editor).toBeVisible()
  await expect(editor).not.toContainText('Anonymous trial.')
  await page.getByRole('link', { name: 'Back to your papers', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your papers', exact: true })).toBeVisible()
  expect(await page.evaluate(() => ({
    source: localStorage.getItem('draftmatter.structured-source.v1'),
    profile: localStorage.getItem('draftmatter.user-settings.v1'),
    login: sessionStorage.getItem('draftmatter.collaboration.oidc.v1'),
  }))).toEqual({ source: privateDraft, profile: 'private-profile-sentinel', login: 'private-login-sentinel' })
  expect(accountRequests).toEqual([])
  expect(errors).toEqual([])
})

test('Enter after the introduction’s first paragraph works when it ends in a citation', async ({ page }) => {
  await page.goto('/demo')
  const first = page.locator('.structured-editor-content > p').filter({ hasText: 'Research articles often separate' })
  await setTrackChanges(page)
  await first.scrollIntoViewIfNeeded()
  await first.evaluate((paragraph) => {
    paragraph.closest<HTMLElement>('.structured-editor-content')!.focus({ preventScroll: true })
    const range = document.createRange()
    range.selectNodeContents(paragraph)
    range.collapse(false)
    window.getSelection()!.removeAllRanges()
    window.getSelection()!.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  const scroller = page.locator('.editor-area')
  const before = await scroller.evaluate(area => area.scrollTop)
  await page.keyboard.press('Enter')
  const wording = first.getByRole('textbox', { name: 'Edit suggested wording' })
  await expect(wording).toBeFocused()
  await page.keyboard.type('This follows the introductory citation.')
  await expect(wording).toHaveText('This follows the introductory citation.')
  await expect(wording).toBeInViewport()
  expect(Math.abs(await scroller.evaluate(area => area.scrollTop) - before)).toBeLessThan(160)
})

test('Enter at the end of the introduction starts an editable tracked paragraph', async ({ page }) => {
  await page.goto('/demo')
  const first = page.locator('.structured-editor-content > p').filter({ hasText: 'Drought phenotyping is a useful demonstration' })
  const second = page.locator('.structured-editor-content > p').filter({ hasText: 'We asked whether a synthetic' })
  await setTrackChanges(page)
  await selectRenderedTextWithMouse(page, first, 'a single runtime.')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Enter')
  const wording = first.getByRole('textbox', { name: 'Edit suggested wording' })
  await expect(wording).toBeFocused()
  await expect(first.locator('.dm-review-paragraph')).toHaveCSS('display', 'block')
  await page.keyboard.type('This paragraph is a proposed addition.')
  await expect(wording).toHaveText('This paragraph is a proposed addition.')
  await expect(second).toContainText('We asked whether')
  const note = page.locator('[data-review-balloon]').filter({ hasText: 'This paragraph is a proposed addition.' })
  await expect(note).toBeVisible()
  await note.locator('.proposal-option').click()
  await note.getByRole('button', { name: 'Accept', exact: true }).click()
  await expect(page.locator('.structured-editor-content > p').filter({ hasText: /^This paragraph is a proposed addition\.$/ })).toBeVisible()
  await expect(second).toContainText('We asked whether')
})
