import { expect, test } from '@playwright/test'

test('keeps legal links on the website base path and supports bookmarks', async ({ page }) => {
  await page.goto('/')
  const footer = page.locator('footer')
  await footer.getByRole('link', { name: 'Terms of use', exact: true }).click()
  await expect(page).toHaveURL(/\/DraftMatter\/#legal\/conditions-utilisation$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Terms of use')
  await expect(page.locator('main')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', { level: 1 })).toBeInViewport()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Terms of use')
  await expect(page.getByRole('heading', { name: 'Testing and data loss', exact: true })).toBeVisible()
  await expect(page.locator('article')).toContainText(/independent backups/i)
  await expect(page.locator('article')).not.toContainText(/Docker|PostgreSQL|\bS3\b|Keycloak|\bVPS\b/i)
  await page.getByRole('link', { name: 'Privacy policy', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Privacy policy')
  await expect(page.getByRole('heading', { level: 1 })).toBeInViewport()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Your paper should be')
  await expect(page.getByRole('heading', { level: 1 })).toBeInViewport()
})

test('shows the complete legal navigation without horizontal overflow on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const links = page.getByRole('navigation', { name: 'Legal information', exact: true })
  await links.scrollIntoViewIfNeeded()
  await expect(links.getByRole('link')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await links.getByRole('link', { name: 'Legal notice', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Legal notice')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
