import { expect, test, type Page } from '@playwright/test'

const KEY = 'draftmatter.writing-toolbar.v1'
const shell = (page: Page) => page.locator('.floating-writing-toolbar-shell')
const toolbar = (page: Page) => page.getByRole('toolbar', { name: 'Formatting toolbar', exact: true })
const reveal = async (page: Page) => {
  await page.getByRole('button', { name: 'Show writing tools', exact: true }).hover()
  await expect(toolbar(page)).toHaveCSS('opacity', '1')
}
const savedSource = (page: Page) => page.evaluate(() => localStorage.getItem('draftmatter.structured-source.v1'))
const assertWithinWindow = async (page: Page) => {
  const bounds = await shell(page).boundingBox()
  const viewport = page.viewportSize()!
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height)
}

test('hides every writing control while idle and reveals them by hover or keyboard focus', async ({ page }) => {
  await page.goto('/draft')
  await expect(page.getByRole('textbox', { name: 'Rendered manuscript editor', exact: true })).toBeVisible()
  await page.mouse.move(5, 800)
  await expect(toolbar(page)).toHaveCSS('opacity', '0')
  await expect(shell(page)).toHaveAttribute('data-visible', 'false')
  await expect(toolbar(page)).toHaveCSS('pointer-events', 'none')
  expect(await toolbar(page).evaluate((element) => getComputedStyle(element, '::after').display)).toBe('none')
  await reveal(page)
  await page.mouse.move(5, 800)
  await expect(toolbar(page)).toHaveCSS('opacity', '0')
  await toolbar(page).getByRole('button', { name: 'Bold', exact: true }).focus()
  await expect(toolbar(page)).toHaveCSS('opacity', '1')
  await page.getByRole('textbox', { name: 'Rendered manuscript editor', exact: true }).focus()
  await expect(toolbar(page)).toHaveCSS('opacity', '0')
})

test('pins writing tools across reload and restores auto-hide when unpinned', async ({ page }) => {
  await page.goto('/draft')
  await reveal(page)
  await toolbar(page).getByRole('button', { name: 'Pin writing tools', exact: true }).click()
  await page.mouse.move(5, 800)
  await expect(toolbar(page)).toHaveCSS('opacity', '1')
  await expect(toolbar(page).getByRole('button', { name: 'Unpin writing tools', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await page.mouse.move(5, 800)
  await expect(shell(page)).toHaveAttribute('data-pinned', 'true')
  await expect(toolbar(page)).toHaveCSS('opacity', '1')
  await toolbar(page).getByRole('button', { name: 'Unpin writing tools', exact: true }).click()
  await page.mouse.move(5, 800)
  await expect(toolbar(page)).toHaveCSS('opacity', '0')
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!).pinned, KEY)).toBe(false)
})

test('drags and docks within the window without changing the manuscript, keeping insertion menus reachable', async ({ page }) => {
  await page.goto('/draft')
  await expect.poll(() => savedSource(page)).not.toBeNull()
  const source = await savedSource(page)
  await reveal(page)
  let handle = await toolbar(page).getByRole('button', { name: 'Move writing tools', exact: true }).boundingBox()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2)
  await page.mouse.down()
  await page.mouse.move(10, 300, { steps: 8 })
  await page.mouse.up()
  await expect(shell(page)).toHaveAttribute('data-dock', 'left')
  expect((await shell(page).boundingBox())!.x).toBe(8)
  await assertWithinWindow(page)
  await reveal(page)
  await toolbar(page).getByRole('button', { name: 'Insert', exact: true }).click()
  let menu = page.locator('.toolbar-insert-menu')
  await expect(menu).toBeVisible()
  let bounds = await menu.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()

  await reveal(page)
  handle = await toolbar(page).getByRole('button', { name: 'Move writing tools', exact: true }).boundingBox()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2)
  await page.mouse.down()
  await page.mouse.move(1434, 954, { steps: 12 })
  await page.mouse.up()
  await expect(shell(page)).toHaveAttribute('data-dock', 'right')
  await assertWithinWindow(page)
  await reveal(page)
  await toolbar(page).getByRole('button', { name: 'Insert', exact: true }).click()
  await expect(menu).toBeVisible()
  bounds = await menu.boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await page.setViewportSize({ width: 840, height: 600 })
  await assertWithinWindow(page)
  expect(await savedSource(page)).toBe(source)
})

test('moves and docks with the keyboard and safely restores a saved position', async ({ page }) => {
  await page.goto('/draft')
  await reveal(page)
  const grip = toolbar(page).getByRole('button', { name: 'Move writing tools', exact: true })
  await grip.focus()
  const initial = await shell(page).boundingBox()
  await page.keyboard.press('ArrowDown')
  await expect(shell(page)).toHaveAttribute('data-dock', 'free')
  expect((await shell(page).boundingBox())!.y).toBe(initial!.y + 12)
  await toolbar(page).getByRole('button', { name: 'Position writing tools', exact: true }).click()
  await expect(page.getByRole('menu', { name: 'Writing tools position', exact: true })).toBeVisible()
  await page.keyboard.press('End')
  await expect(page.getByRole('menuitem', { name: 'Dock right', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(shell(page)).toHaveAttribute('data-dock', 'right')
  await page.reload()
  await expect(shell(page)).toHaveAttribute('data-dock', 'right')
  await assertWithinWindow(page)
  await reveal(page)
  await grip.focus()
  await page.keyboard.press('Home')
  await expect(shell(page)).toHaveAttribute('data-dock', 'center')
})

test.describe('touch writing tools', () => {
  test.use({ hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 } })
  test('keeps tools visible and bounded without requiring a hover gesture', async ({ page }) => {
    await page.goto('/draft')
    await expect(toolbar(page)).toHaveCSS('opacity', '1')
    await expect(toolbar(page).getByRole('button', { name: 'Insert citation', exact: true })).toBeVisible()
    await assertWithinWindow(page)
    await toolbar(page).getByRole('button', { name: 'Position writing tools', exact: true }).tap()
    await page.getByRole('menuitem', { name: 'Dock left', exact: true }).tap()
    await expect(shell(page)).toHaveAttribute('data-dock', 'left')
    await assertWithinWindow(page)
  })
})
