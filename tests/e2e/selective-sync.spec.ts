import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { expect, test } from '@playwright/test'

test('selects data explicitly and preserves both sides of a manuscript conflict', async ({ page }) => {
  await page.goto('/tests/e2e/fixtures/selective-sync.html')
  const panel = page.getByRole('region', { name: 'Selective synchronization' })
  const manuscript = panel.locator('.selective-sync-file').filter({ has: page.getByRole('checkbox', { name: 'Follow paper.qmd', exact: true }) })
  await expect(manuscript).toContainText('Both the local and online copies changed')
  await expect(panel.getByRole('checkbox', { name: 'Follow paper.qmd', exact: true })).toBeChecked()
  await expect(panel.getByRole('checkbox', { name: 'Follow data/observations.csv', exact: true })).not.toBeChecked()
  await mkdir(resolve('test-results/selective-sync'), { recursive: true })
  await page.screenshot({ path: resolve('test-results/selective-sync/conflict.png'), fullPage: true })
  await panel.getByRole('checkbox', { name: 'Follow data/observations.csv', exact: true }).check()
  await expect(panel.getByRole('button', { name: 'Sync now', exact: true })).toBeEnabled()
  await manuscript.getByRole('button', { name: 'Compare copies', exact: true }).click()
  const comparison = manuscript.getByRole('region', { name: 'Compare copies of paper.qmd', exact: true })
  await expect(comparison.locator('article').filter({ has: page.getByRole('heading', { name: 'Local copy', exact: true }) })).toContainText('A local revision.')
  await expect(comparison.locator('article').filter({ has: page.getByRole('heading', { name: 'Online copy', exact: true }) })).toContainText('An online revision.')
  await expect(comparison.locator('textarea, input, [contenteditable="true"]')).toHaveCount(0)
  await comparison.scrollIntoViewIfNeeded()
  await page.screenshot({ path: resolve('test-results/selective-sync/comparison.png'), fullPage: true })
  await manuscript.getByRole('button', { name: 'Keep both', exact: true }).click()
  await expect(manuscript).toContainText('Up to date')
  const copies = await page.evaluate(() => (window as unknown as { syncFixture: { copies(): { local: Record<string, string>; remote: Record<string, string> } } }).syncFixture.copies())
  expect(copies.local['paper.qmd']).toContain('An online revision')
  expect(copies.remote['paper.qmd']).toContain('An online revision')
  const conflict = Object.keys(copies.local).find((path) => /^paper\.conflict-local-[a-f0-9]+\.qmd$/.test(path))!
  expect(copies.local[conflict]).toContain('A local revision')
  expect(copies.remote[conflict]).toContain('A local revision')
  expect(copies.remote['data/observations.csv']).toContain('week,area')
})

test('rejects a conflict choice when the online file changed after inspection', async ({ page }) => {
  await page.goto('/tests/e2e/fixtures/selective-sync.html')
  const manuscript = page.locator('.selective-sync-file').filter({ has: page.getByRole('checkbox', { name: 'Follow paper.qmd', exact: true }) })
  await expect(manuscript).toContainText('Both the local and online copies changed')
  await manuscript.getByRole('button', { name: 'Compare copies', exact: true }).click()
  await expect(manuscript.getByRole('region', { name: 'Compare copies of paper.qmd', exact: true })).toContainText('An online revision.')
  await page.evaluate(() => (window as unknown as { syncFixture: { editOnline(path: string, text: string): void } }).syncFixture.editOnline('paper.qmd', 'Newest concurrent online revision'))
  await manuscript.getByRole('button', { name: 'Keep local', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('changed since the conflict was displayed')
  await expect(manuscript.getByRole('status')).toContainText('The copies changed after this preview')
  for (const name of ['Keep local', 'Use online', 'Keep both']) await expect(manuscript.getByRole('button', { name, exact: true })).toBeDisabled()
  const copies = await page.evaluate(() => (window as unknown as { syncFixture: { copies(): { local: Record<string, string>; remote: Record<string, string> } } }).syncFixture.copies())
  expect(copies.local['paper.qmd']).toContain('A local revision')
  expect(copies.remote['paper.qmd']).toBe('Newest concurrent online revision')
  await manuscript.getByRole('button', { name: 'Compare copies', exact: true }).click()
  await expect(manuscript.getByRole('region', { name: 'Compare copies of paper.qmd', exact: true })).toContainText('Newest concurrent online revision')
  await expect(manuscript.getByRole('status')).toHaveCount(0)
  await expect(manuscript.getByRole('button', { name: 'Keep both', exact: true })).toBeEnabled()
})
