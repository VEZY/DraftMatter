import { expect, test } from '@playwright/test'

declare global { interface Window { localGitFixture: { operations(): { kind: string; request?: unknown }[]; initialized(): boolean; source(): string } } }
const rail = (page: import('@playwright/test').Page) => page.getByRole('navigation', { name: 'Workspace navigation', exact: true })
const gitPanel = (page: import('@playwright/test').Page) => page.getByRole('complementary', { name: 'Git', exact: true })

test('keeps Git commits separate from recovery and only sends selected files to a local commit', async ({ page }, testInfo) => {
  await page.goto('/tests/e2e/fixtures/local-git.html')
  const manuscript = page.getByRole('article', { name: 'Editable manuscript', exact: true })
  await expect(manuscript).toContainText('The current article stays editable while Git is open.')
  await expect(rail(page).getByRole('button', { name: 'Git', exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.localGitFixture.operations())).toEqual([])
  await rail(page).getByRole('button', { name: 'Git', exact: true }).click()
  const panel = gitPanel(page)
  await expect(panel).toBeVisible()
  const paper = panel.getByRole('checkbox', { name: 'Include paper.md', exact: true })
  const data = panel.getByRole('checkbox', { name: 'Include data/observations.csv', exact: true })
  await expect(paper).not.toBeChecked()
  await expect(data).not.toBeChecked()
  await panel.getByRole('button', { name: 'View changes in paper.md', exact: true }).click()
  await expect(panel).toContainText('Previous result.')
  await panel.getByRole('button', { name: 'Source', exact: true }).click()
  await expect(panel.locator('pre')).toContainText('+Revised result.')
  await panel.getByRole('button', { name: 'Close Git diff', exact: true }).click()
  await paper.check()
  await panel.getByLabel('Commit message', { exact: true }).fill('Revise the article')
  await panel.getByRole('button', { name: 'Create commit', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'View commit bbbbbbbb', exact: true })).toBeVisible()
  const commits = await page.evaluate(() => window.localGitFixture.operations().filter((entry) => entry.kind === 'commit'))
  expect(commits).toEqual([{ kind: 'commit', request: { root: '/fixture/local-git', paths: ['paper.md'], message: 'Revise the article' } }])
  expect(await page.evaluate(() => window.localGitFixture.operations().some((entry) => ['fetch', 'pull', 'push'].includes(entry.kind)))).toBe(false)
  await expect(data).not.toBeChecked()
  await panel.getByRole('button', { name: 'View commit bbbbbbbb', exact: true }).click()
  await expect(panel).toContainText('Revised result.')
  await expect(manuscript).toContainText('The current article stays editable while Git is open.')
  await panel.getByRole('button', { name: 'Fetch', exact: true }).click()
  await panel.getByRole('button', { name: 'Push', exact: true }).click()
  await panel.getByRole('button', { name: 'Pull fast-forward', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('Keep uncommitted files before pulling')
  expect((await page.evaluate(() => window.localGitFixture.operations())).filter((entry) => ['fetch', 'pull', 'push'].includes(entry.kind)).map((entry) => entry.kind)).toEqual(['fetch', 'push', 'pull'])
  await rail(page).getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Recovery history', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: testInfo.outputPath('local-git-panel.png') })
})

test('offers Git initialization in the project menu without automatically initializing or committing', async ({ page }) => {
  await page.goto('/tests/e2e/fixtures/local-git.html?git=off')
  await expect(page.getByRole('article', { name: 'Editable manuscript', exact: true })).toBeVisible()
  await expect(rail(page).getByRole('button', { name: 'Git', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => window.localGitFixture.operations())).toEqual([])
  await page.locator('.project-switcher').click()
  await page.getByRole('button', { name: /Initialize Git/ }).click()
  await expect(rail(page).getByRole('button', { name: 'Git', exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.localGitFixture.operations())).toEqual([{ kind: 'initialize', request: '/fixture/local-git' }])
})

test('reloads the open manuscript after an explicit successful fast-forward pull', async ({ page }) => {
  await page.goto('/tests/e2e/fixtures/local-git.html?git=clean')
  await rail(page).getByRole('button', { name: 'Git', exact: true }).click()
  const panel = gitPanel(page)
  await panel.getByRole('button', { name: 'Pull fast-forward', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Editable manuscript', exact: true })).toContainText('A fast-forwarded article from the configured remote.')
  expect((await page.evaluate(() => window.localGitFixture.operations())).filter((entry) => ['fetch', 'pull', 'push'].includes(entry.kind))).toEqual([{ kind: 'pull', request: { root: '/fixture/local-git' } }])
})
