import katex from 'katex'

function xml(value: string) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;')
}

/** Native MathML needs no downloaded fonts, script, or stylesheet in exported HTML/PDF. */
export function publicationMathml(tex: string, displayMode = false) {
  if (tex.length > 100_000 || /\\(?:href|url|includegraphics|htmlClass|htmlId|htmlStyle|htmlData)\b/.test(tex)) throw new Error('Equation contains a command or payload disabled in publication exports.')
  try {
    return katex.renderToString(tex, { displayMode, output: 'mathml', throwOnError: true, strict: 'ignore', trust: false, maxExpand: 500, maxSize: 20 })
  } catch { throw new Error('An equation could not be rendered. Check its TeX before exporting.') }
}

interface MathNode { name: string; attributes: Record<string, string>; children: Array<MathNode | string> }

function decoded(value: string) {
  return value.replace(/&#(x[\da-f]+|\d+);|&(amp|lt|gt|quot|apos);/gi, (_raw, numeric: string | undefined, named: string | undefined) => numeric
    ? String.fromCodePoint(numeric[0].toLowerCase() === 'x' ? Number.parseInt(numeric.slice(1), 16) : Number(numeric))
    : ({ amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" }[named!.toLowerCase()] ?? ''))
}

// Parse only XML generated by our bounded KaTeX call; never manuscript-supplied XML.
function parseGeneratedMathml(value: string): MathNode {
  const root: MathNode = { name: 'root', attributes: {}, children: [] }
  const stack = [root]
  for (const match of value.matchAll(/<[^>]+>|[^<]+/g)) {
    const token = match[0]
    if (token.startsWith('</')) { stack.pop(); continue }
    if (token.startsWith('<')) {
      const name = token.match(/^<([\w:-]+)/)?.[1]
      if (!name) continue
      const node: MathNode = { name, attributes: Object.fromEntries([...token.matchAll(/([\w:-]+)="([^"]*)"/g)].map((attribute) => [attribute[1], decoded(attribute[2])])), children: [] }
      stack.at(-1)!.children.push(node)
      if (!token.endsWith('/>')) stack.push(node)
    } else stack.at(-1)!.children.push(decoded(token))
  }
  return root
}

function run(value: string, normal = false) {
  return `<m:r>${normal ? '<m:rPr><m:nor/></m:rPr>' : ''}<m:t xml:space="preserve">${xml(value)}</m:t></m:r>`
}

function omml(node: MathNode | string): string {
  if (typeof node === 'string') return node ? run(node) : ''
  const children = node.children.filter((child): child is MathNode => typeof child !== 'string')
  const content = () => node.children.map(omml).join('')
  const at = (index: number) => children[index] ? omml(children[index]) : ''
  const text = () => node.children.filter((child): child is string => typeof child === 'string').join('')
  switch (node.name) {
    case 'annotation': case 'annotation-xml': return ''
    case 'root': case 'span': case 'math': case 'mrow': case 'mstyle': case 'mpadded': case 'mtd': case 'mtr': return content()
    case 'semantics': return at(0)
    case 'mi': case 'mn': case 'mo': return run(text(), node.attributes.mathvariant === 'normal')
    case 'mtext': return run(text(), true)
    case 'mspace': return run(' ')
    case 'mfrac': return `<m:f><m:num>${at(0)}</m:num><m:den>${at(1)}</m:den></m:f>`
    case 'msup': return `<m:sSup><m:e>${at(0)}</m:e><m:sup>${at(1)}</m:sup></m:sSup>`
    case 'msub': return `<m:sSub><m:e>${at(0)}</m:e><m:sub>${at(1)}</m:sub></m:sSub>`
    case 'msubsup': return `<m:sSubSup><m:e>${at(0)}</m:e><m:sub>${at(1)}</m:sub><m:sup>${at(2)}</m:sup></m:sSubSup>`
    case 'msqrt': return `<m:rad><m:radPr><m:degHide m:val="1"/></m:radPr><m:deg/><m:e>${content()}</m:e></m:rad>`
    case 'mroot': return `<m:rad><m:deg>${at(1)}</m:deg><m:e>${at(0)}</m:e></m:rad>`
    case 'mover': {
      const accent = children[1]?.children.filter((child): child is string => typeof child === 'string').join('')
      return node.attributes.accent === 'true'
        ? `<m:acc><m:accPr><m:chr m:val="${xml(accent ?? '^')}"/></m:accPr><m:e>${at(0)}</m:e></m:acc>`
        : `<m:limUpp><m:e>${at(0)}</m:e><m:lim>${at(1)}</m:lim></m:limUpp>`
    }
    case 'munder': return `<m:limLow><m:e>${at(0)}</m:e><m:lim>${at(1)}</m:lim></m:limLow>`
    case 'munderover': return `<m:limUpp><m:e><m:limLow><m:e>${at(0)}</m:e><m:lim>${at(1)}</m:lim></m:limLow></m:e><m:lim>${at(2)}</m:lim></m:limUpp>`
    case 'mtable': return `<m:m>${children.map((row) => `<m:mr>${row.children.filter((child): child is MathNode => typeof child !== 'string').map((cell) => `<m:e>${omml(cell)}</m:e>`).join('')}</m:mr>`).join('')}</m:m>`
    case 'mphantom': return `<m:phant><m:phantPr><m:show m:val="0"/></m:phantPr><m:e>${content()}</m:e></m:phant>`
    case 'menclose': return `<m:borderBox><m:e>${content()}</m:e></m:borderBox>`
    default: throw new Error(`The equation uses a mathematical structure not yet supported by Word export (${node.name}). Use HTML/PDF or revise it before exporting.`)
  }
}

/** Editable native Office Math, generated from the same math tree as HTML/PDF. */
export function publicationOfficeMath(tex: string, displayMode = false) {
  return `<m:oMath>${omml(parseGeneratedMathml(publicationMathml(tex, displayMode)))}</m:oMath>`
}
